/**
 * Returns a high-definition real photo for a vocabulary word
 */
export function getRealPhotoForWord(item) {
  if (!item) return null;
  if (
    item.image &&
    typeof item.image === "string" &&
    item.image.startsWith("http")
  ) {
    return item.image;
  }
  const vnKey = (item.vn || item.targetVN || "").trim().toLowerCase();
  const enKey = (item.en || item.targetEN || "").trim().toLowerCase();
  const emojiKey = (item.emoji || "").trim();

  if (REAL_PHOTOS_MAP[vnKey]) return REAL_PHOTOS_MAP[vnKey];
  if (REAL_PHOTOS_MAP[enKey]) return REAL_PHOTOS_MAP[enKey];
  if (EMOJI_PHOTOS_MAP[emojiKey]) return EMOJI_PHOTOS_MAP[emojiKey];

  return null;
}

/**
 * Returns a real photo for a math counting or comparing item
 */
export function getRealPhotoForMath(itemEmoji, itemTitle) {
  if (EMOJI_PHOTOS_MAP[itemEmoji]) {
    return EMOJI_PHOTOS_MAP[itemEmoji];
  }
  const lowerTitle = (itemTitle || "").toLowerCase();
  for (const [k, v] of Object.entries(REAL_PHOTOS_MAP)) {
    if (lowerTitle.includes(k)) return v;
  }
  return null;
}

/**
 * Returns the realistic 3D asset for a pet
 */
export function get3DPetAsset(pet) {
  if (!pet) return PETS_3D_ASSETS.cat;
  const pId = (pet.id || "").toLowerCase();
  if (PETS_3D_ASSETS[pId]) {
    return { ...pet, ...PETS_3D_ASSETS[pId] };
  }
  // Try matching by name or emoji
  if (
    (pet.name && pet.name.toLowerCase().includes("cún")) ||
    (pet.name && pet.name.toLowerCase().includes("chó"))
  ) {
    return { ...pet, ...PETS_3D_ASSETS.dog };
  }
  if (pet.name && pet.name.toLowerCase().includes("thỏ")) {
    return { ...pet, ...PETS_3D_ASSETS.bunny };
  }
  if (pet.name && pet.name.toLowerCase().includes("trúc")) {
    return { ...pet, ...PETS_3D_ASSETS.panda };
  }
  if (pet.name && pet.name.toLowerCase().includes("cụt")) {
    return { ...pet, ...PETS_3D_ASSETS.penguin };
  }
  return { ...pet, ...PETS_3D_ASSETS.cat };
}
